CREATE TABLE tracked_repository (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    full_name VARCHAR(201) NOT NULL,
    github_url VARCHAR(512) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX tracked_repository_full_name_unique ON tracked_repository (lower(full_name));
CREATE UNIQUE INDEX tracked_repository_single_active ON tracked_repository (active) WHERE active = TRUE;
CREATE TABLE repository_selection_lock (id INTEGER PRIMARY KEY CHECK (id = 1));
