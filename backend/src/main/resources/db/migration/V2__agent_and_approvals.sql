CREATE TABLE chat_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES tracked_repository(id),
    title VARCHAR(160) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    busy BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_session(id),
    role VARCHAR(16) NOT NULL CHECK (role IN ('USER','ASSISTANT')),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX chat_message_session_idx ON chat_message(session_id, id);
CREATE TABLE issue_proposal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_session(id),
    repository_id BIGINT NOT NULL REFERENCES tracked_repository(id),
    title VARCHAR(256) NOT NULL,
    body TEXT NOT NULL,
    labels TEXT NOT NULL DEFAULT '',
    state VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING','REJECTED','EXECUTING','SUCCEEDED','UNKNOWN')),
    github_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX issue_proposal_session_idx ON issue_proposal(session_id, id);
CREATE TABLE tool_execution_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_session(id),
    tool_name VARCHAR(100) NOT NULL,
    success BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX tool_log_session_idx ON tool_execution_log(session_id, id);
